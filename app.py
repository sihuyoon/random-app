# (1) 데이터 구조: 스코빌 단계와 기본 위험 등급 리스트
# 1등급이 가장 위험, 7등급이 가장 안전함
base_grades = [7, 6, 5, 4, 3, 2, 1]

scoville_names = [
    "1천 스코빌 미만 (진라면 순한맛 수준)", 
    "1천 ~ 1만 스코빌 (신라면, 청양고추 입문)", 
    "1만 ~ 5만 스코빌 (불닭볶음면 수준)", 
    "5만 ~ 10만 스코빌 (핵불닭, 타이 고추)", 
    "10만 ~ 50만 스코빌 (하바네로 고추)", 
    "50만 ~ 150만 스코빌 (부트 졸로키아)", 
    "150만 스코빌 이상 (캐롤라이나 리퍼, 사신 수준)"
]

# (2) 함수: 나이와 선택 메뉴를 받아 위험 등급 산출
def calculate_risk(level_index, age):
    grade = base_grades[level_index]
    
    # 나이가 15세 미만이거나 60세 이상이면 매운맛에 더 취약함 (위험도 1단계 상승)
    if age < 15 or age >= 60:
        grade = grade - 1
        
    # (3) 조건문: 나이가 70세 이상이면 무조건 위험등급 4등급 이상(숫자 4 이하)으로 고정
    if age >= 70:
        if grade > 4:
            grade = 4
            
    # 등급이 1보다 작아지면 1로 고정 (최대 위험 한계치)
    if grade < 1:
        grade = 1
        
    return grade

# --- 프로그램 시작 ---
print("🔥 [업그레이드] 스코빌 지수 정밀 위험도 측정기 🔥")
for i in range(len(scoville_names)):
    print(f"{i + 1}. {scoville_names[i]}")

print("-" * 45)

# 사용자 입력
choice_num = int(input("도전할 매운맛 번호를 선택하세요 (1~7): "))
user_age = int(input("도전자의 나이를 입력하세요: "))

print("\n...🔥 위장 타격 가능성 계산 중 🔥...\n")

# 리스트 인덱스에 맞게 -1 해주기
level_idx = choice_num - 1 

# 함수 호출하여 최종 등급 받기
final_grade = calculate_risk(level_idx, user_age)

# 결과 출력
print("=============================================")
print(f" ✅ 선택한 매운맛: {scoville_names[level_idx]}")
print(f" ✅ 도전자 나이: {user_age}세")
print(f" 🚨 최종 위험 등급: {final_grade}등급 🚨")

# 고령자이면서 특정 스코빌(10만 이상, 즉 5번 메뉴 이상)을 골랐을 때 강력 경고
if user_age >= 70 and choice_num >= 5:
    print("\n ⚠️ [긴급 경고] 고령자의 10만 스코빌 이상 섭취는 절대 금지!")
print("=============================================\n")

